import vm from 'node:vm';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
let now=0,storage='',failSave=false;
const page={id:'page-1',name:'Test',children:[],getPluginData:()=>storage,setPluginData:(_,v)=>{if(failSave)throw Error('save failed');storage=v;}};
const context=vm.createContext({__html__:'',Date:{now:()=>now},setTimeout:fn=>{now+=300;fn();},figma:{currentPage:page,showUI(){},ui:{postMessage(){}}}});
vm.runInContext(readFileSync('figma-plugin/code.js','utf8'),context);
const node=(id,x,y,width=1440)=>({id,type:'FRAME',x,y,width,height:900,findAll:()=>[]});
const request=(command,jobId)=>context.handle({command,jobId,gap:500});
await request('BEGIN','first');const first=node('first',400,-300);page.children.push(first);
assert.equal((await request('COMMIT','first')).ok,true);assert.equal(first.x,0);assert.equal(first.y,0);
const baseline=storage;
await request('BEGIN','late');
await assert.rejects(request('COMMIT','late'),/未确认新增画板/);
assert.equal(storage,baseline,'timeout must preserve last success');
const late=node('late',22,33);page.children.push(late);
assert.equal((await request('COMMIT','late')).ok,true);assert.equal(late.x,1940);assert.equal(late.y,0);
assert.equal((await request('COMMIT','late')).nodeId,'late','commit retry is idempotent');
await request('BEGIN','multiple');const a=node('a',12,13),b=node('b',14,15);page.children.push(a,b);
const stable=storage;await assert.rejects(request('COMMIT','multiple'),/多个新增/);assert.equal(a.x,12);assert.equal(storage,stable);
await request('CANCEL','multiple');
await request('BEGIN','rollback');const c=node('c',123,456);page.children.push(c);failSave=true;
await assert.rejects(request('COMMIT','rollback'),/save failed/);assert.equal(c.x,123);assert.equal(c.y,456);assert.equal(storage,stable);
failSave=false;await request('COMMIT','rollback');assert.equal(c.x,3880);
await request('BEGIN','switch');context.figma.currentPage={id:'different'};
await assert.rejects(request('COMMIT','switch'),/切换/);
console.log('PASS: origin, +500, timeout retention, late-import retry, idempotency, ambiguity refusal, rollback, page-switch refusal.');
